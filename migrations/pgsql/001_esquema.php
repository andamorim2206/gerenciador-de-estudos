<?php

// Esquema completo no PostgreSQL: equivale às migrações 001–004 do SQLite, já no estado final.
// Horários em timestamp(0) no horário de Brasília (a conexão usa TimeZone=America/Sao_Paulo).
//
//   usuarios, materias, tarefas      contas, matérias e calendário de tarefas
//   sessoes_foco                     única fonte de XP e de moedas
//   progresso_neuronio               XP ← tempo das sessões concluídas
//   carteiras + transacoes_moedas    moedas ← quantidade de sessões concluídas (o extrato é a fonte da verdade)
//   itens_loja, itens_usuario, itens_equipados   loja de cosméticos

return function (PDO $pdo): void {
    // citext: e-mail e nome de matéria comparados sem diferenciar maiúsculas (como o COLLATE NOCASE do SQLite).
    $pdo->exec('CREATE EXTENSION IF NOT EXISTS citext SCHEMA public');

    $pdo->exec('
        CREATE TABLE usuarios (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email public.citext NOT NULL UNIQUE,
            nome text NOT NULL CHECK (char_length(nome) BETWEEN 1 AND 60),
            senha_hash text NOT NULL,
            criado_em timestamp(0) NOT NULL
        )
    ');

    // usuario_id NULL: matéria sem dono, herdada pelo primeiro usuário criado.
    $pdo->exec('
        CREATE TABLE materias (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
            nome public.citext NOT NULL CHECK (char_length(nome) BETWEEN 1 AND 60),
            cor integer NOT NULL DEFAULT 0 CHECK (cor BETWEEN 0 AND 7),
            arquivada_em timestamp(0),
            criada_em timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
        )
    ');
    $pdo->exec('CREATE UNIQUE INDEX idx_materias_usuario_nome ON materias(usuario_id, nome)');

    $pdo->exec('
        CREATE TABLE tarefas (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            materia_id integer NOT NULL REFERENCES materias(id) ON DELETE CASCADE,
            titulo text NOT NULL,
            data date NOT NULL,
            concluida integer NOT NULL DEFAULT 0 CHECK (concluida IN (0, 1)),
            minutos integer NOT NULL DEFAULT 0 CHECK (minutos >= 0),
            serie text,
            criada_em timestamp(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)
        )
    ');
    $pdo->exec('CREATE INDEX idx_tarefas_data ON tarefas(data)');
    $pdo->exec('CREATE INDEX idx_tarefas_serie ON tarefas(serie)');
    $pdo->exec('CREATE INDEX idx_tarefas_materia ON tarefas(materia_id)');

    $pdo->exec("
        CREATE TABLE sessoes_foco (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
            materia_id integer NOT NULL REFERENCES materias(id) ON DELETE RESTRICT,
            iniciada_em timestamp(0) NOT NULL,
            encerrada_em timestamp(0),
            duracao_planejada_min integer NOT NULL CHECK (duracao_planejada_min BETWEEN 10 AND 180),
            duracao_real_min integer CHECK (duracao_real_min >= 0),
            status text NOT NULL DEFAULT 'em_andamento'
                CHECK (status IN ('em_andamento', 'concluida', 'abandonada')),
            recompensada_em timestamp(0),
            criada_em timestamp(0) NOT NULL,
            CHECK (status <> 'concluida' OR (encerrada_em IS NOT NULL AND recompensada_em IS NOT NULL
                AND duracao_real_min IS NOT NULL AND duracao_real_min <= duracao_planejada_min)),
            CHECK (status = 'concluida' OR recompensada_em IS NULL)
        )
    ");
    $pdo->exec('CREATE INDEX idx_sessoes_usuario_status ON sessoes_foco(usuario_id, status, iniciada_em)');
    $pdo->exec('CREATE INDEX idx_sessoes_materia ON sessoes_foco(materia_id)');
    // No máximo uma sessão em andamento por usuário, garantido pelo banco.
    $pdo->exec("CREATE UNIQUE INDEX idx_sessoes_uma_ativa ON sessoes_foco(usuario_id) WHERE status = 'em_andamento'");

    $pdo->exec('
        CREATE TABLE progresso_neuronio (
            usuario_id integer PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
            xp_total integer NOT NULL DEFAULT 0 CHECK (xp_total >= 0),
            estagio_atual integer NOT NULL DEFAULT 0 CHECK (estagio_atual >= 0),
            ultimo_estagio_visto integer NOT NULL DEFAULT 0,
            atualizado_em timestamp(0) NOT NULL
        )
    ');

    $pdo->exec('
        CREATE TABLE carteiras (
            usuario_id integer PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
            saldo integer NOT NULL DEFAULT 0 CHECK (saldo >= 0),
            atualizado_em timestamp(0) NOT NULL
        )
    ');

    $pdo->exec("
        CREATE TABLE itens_loja (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            slug text NOT NULL UNIQUE,
            nome text NOT NULL,
            descricao text NOT NULL,
            categoria text NOT NULL CHECK (categoria IN ('skin_neuronio', 'cenario', 'efeito')),
            preco integer NOT NULL CHECK (preco > 0),
            ativo integer NOT NULL DEFAULT 1 CHECK (ativo IN (0, 1)),
            ordem integer NOT NULL DEFAULT 0,
            criada_em timestamp(0) NOT NULL
        )
    ");

    $pdo->exec('
        CREATE TABLE itens_usuario (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
            item_id integer NOT NULL REFERENCES itens_loja(id) ON DELETE RESTRICT,
            preco_pago integer NOT NULL CHECK (preco_pago > 0),
            adquirido_em timestamp(0) NOT NULL,
            UNIQUE (usuario_id, item_id)
        )
    ');

    $pdo->exec("
        CREATE TABLE itens_equipados (
            usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
            categoria text NOT NULL CHECK (categoria IN ('skin_neuronio', 'cenario', 'efeito')),
            item_usuario_id integer NOT NULL REFERENCES itens_usuario(id) ON DELETE CASCADE,
            PRIMARY KEY (usuario_id, categoria)
        )
    ");

    $pdo->exec("
        CREATE TABLE transacoes_moedas (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
            tipo text NOT NULL CHECK (tipo IN ('ganho_sessao', 'compra', 'ajuste')),
            valor integer NOT NULL CHECK (valor <> 0),
            saldo_apos integer NOT NULL CHECK (saldo_apos >= 0),
            sessao_id integer UNIQUE REFERENCES sessoes_foco(id) ON DELETE RESTRICT,
            item_usuario_id integer UNIQUE REFERENCES itens_usuario(id) ON DELETE RESTRICT,
            motivo text,
            criada_em timestamp(0) NOT NULL,
            CHECK (tipo <> 'ganho_sessao' OR (sessao_id IS NOT NULL AND valor = 1 AND item_usuario_id IS NULL)),
            CHECK (tipo <> 'compra' OR (item_usuario_id IS NOT NULL AND valor < 0 AND sessao_id IS NULL)),
            CHECK (tipo <> 'ajuste' OR (motivo IS NOT NULL AND sessao_id IS NULL AND item_usuario_id IS NULL))
        )
    ");
    $pdo->exec('CREATE INDEX idx_transacoes_usuario ON transacoes_moedas(usuario_id, id)');

    // O extrato é só de inclusão, e sessões concluídas (que já geraram XP e moeda) não mudam.
    $pdo->exec("
        CREATE FUNCTION impedir_alteracao() RETURNS trigger LANGUAGE plpgsql AS \$\$
        BEGIN
            RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = 'restrict_violation';
        END
        \$\$
    ");
    $pdo->exec("
        CREATE TRIGGER transacoes_imutaveis BEFORE UPDATE OR DELETE ON transacoes_moedas
        FOR EACH ROW EXECUTE FUNCTION impedir_alteracao('transações de moedas são imutáveis')
    ");
    $pdo->exec("
        CREATE TRIGGER transacoes_sem_truncate BEFORE TRUNCATE ON transacoes_moedas
        FOR EACH STATEMENT EXECUTE FUNCTION impedir_alteracao('transações de moedas são imutáveis')
    ");
    $pdo->exec("
        CREATE TRIGGER sessoes_concluidas_imutaveis BEFORE UPDATE OR DELETE ON sessoes_foco
        FOR EACH ROW WHEN (OLD.status = 'concluida')
        EXECUTE FUNCTION impedir_alteracao('sessões concluídas são imutáveis')
    ");

    $agora = date('Y-m-d H:i:s');
    $itens = $pdo->prepare('INSERT INTO itens_loja (slug, nome, descricao, categoria, preco, ordem, criada_em) VALUES (?, ?, ?, ?, ?, ?, ?)');
    foreach ([
        ['skin-aurora', 'Skin Aurora', 'Dendritos em degradê de verde-água a violeta.', 'skin_neuronio', 3, 1],
        ['skin-neon', 'Skin Neon', 'Um neurônio magenta que brilha no escuro.', 'skin_neuronio', 5, 2],
        ['cenario-noite', 'Noite estrelada', 'Seu neurônio sob um céu de estrelas.', 'cenario', 6, 3],
        ['cenario-biblioteca', 'Biblioteca', 'Tons quentes de madeira e papel antigo.', 'cenario', 6, 4],
        ['efeito-faiscas', 'Faíscas sinápticas', 'Impulsos elétricos percorrendo o axônio.', 'efeito', 8, 5],
    ] as [$slug, $nome, $descricao, $categoria, $preco, $ordem]) {
        $itens->execute([$slug, $nome, $descricao, $categoria, $preco, $ordem, $agora]);
    }
};
